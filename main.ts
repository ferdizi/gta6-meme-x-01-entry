function drawGhost(layer: Layer, x: number, y: number, w: number, h: number): void {
  // make.fun ghost: dome top, straight sides, three scallops at the bottom.
  const pts: Pt[] = [];
  const cx = x + w / 2;
  const r = w / 2;
  const domeTop = y;
  const sideTop = y + r;
  const bottom = y + h;
  for (let k = 0; k <= 16; k++) {
    const t = Math.PI + (k / 16) * Math.PI; // left -> right over the top
    pts.push([cx + r * Math.cos(t), sideTop + r * Math.sin(t)]);
  }
  // right side down to bottom
  pts.push([x + w, bottom - r * 0.42]);
  // three scallops (right -> left), each a half-circle dipping up
  const sw = w / 3;
  for (let s = 2; s >= 0; s--) {
    const sx0 = x + s * sw;
    const scx = sx0 + sw / 2;
    for (let k = 0; k <= 8; k++) {
      const t = (k / 8) * Math.PI; // 0..PI, right -> left along bottom of arc
      pts.push([scx + (sw / 2) * Math.cos(t), bottom - r * 0.42 + (r * 0.42) * Math.sin(t)]);
    }
  }
  pts.push([x, sideTop]);
  layer.fillPoly(pts, [255, 255, 255]);
  // eyes
  layer.ellipse(cx - w * 0.17, y + h * 0.38, w * 0.075, h * 0.085, INK);
  layer.ellipse(cx + w * 0.17, y + h * 0.38, w * 0.075, h * 0.085, INK);
  // pink star on the cheek
  const star: Pt[] = [];
  const sx = cx + w * 0.3;
  const sy = y + h * 0.58;
  const sr = w * 0.14;
  for (let k = 0; k < 10; k++) {
    const t = -Math.PI / 2 + (k / 10) * Math.PI * 2;
    const rr = k % 2 === 0 ? sr : sr * 0.45;
    star.push([sx + rr * Math.cos(t), sy + rr * Math.sin(t)]);
  }
  layer.fillPoly(star, [236, 72, 153]);
}

