function parsePath(cmds: string): Pt[][] {
  const tokens = cmds.match(/[MLQZ]|-?\d+/g) || [];
  const subs: Pt[][] = [];
  let cur: Pt[] = [];
  let pen: Pt = [0, 0];
  let i = 0;
  const num = (): number => parseInt(tokens[i++], 10);
  while (i < tokens.length) {
    const t = tokens[i++];
    if (t === "M") {
      if (cur.length > 0) subs.push(cur);
      cur = [];
      pen = [num(), num()];
      cur.push(pen);
    } else if (t === "L") {
      pen = [num(), num()];
      cur.push(pen);
    } else if (t === "Q") {
      const c: Pt = [num(), num()];
      const e: Pt = [num(), num()];
      const p0 = pen;
      for (let s = 1; s <= 12; s++) {
        const u = s / 12;
        const w0 = (1 - u) * (1 - u);
        const w1 = 2 * (1 - u) * u;
        const w2 = u * u;
        cur.push([w0 * p0[0] + w1 * c[0] + w2 * e[0], w0 * p0[1] + w1 * c[1] + w2 * e[1]]);
      }
      pen = e;
    } else if (t === "Z") {
      if (cur.length > 0) subs.push(cur);
      cur = [];
    }
  }
  if (cur.length > 0) subs.push(cur);
  return subs;
}

interface GlyphBmp {
  w: number; // device px
  h: number;
  ox: number; // device px offset of bitmap left edge from glyph origin
  oy: number; // device px offset of bitmap top edge from baseline
  a: Uint8Array; // alpha 0..255, w*h
}

const glyphCache = new Map<string, GlyphBmp>();

function glyphBitmap(font: Font, ch: string, pxSize: number, ss: number): GlyphBmp {
  const key = `${font === FONT_BOLD ? "B" : "R"}${ch}@${pxSize}x${ss}`;
  const hit = glyphCache.get(key);
  if (hit) return hit;
  const entry = font[ch];
  const empty: GlyphBmp = { w: 0, h: 0, ox: 0, oy: 0, a: new Uint8Array(0) };
  if (!entry || !entry[1]) {
    glyphCache.set(key, empty);
    return empty;
  }
  const scale = (pxSize * ss) / 256; // device px per data unit
  const subs = parsePath(entry[1]);
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const s of subs) {
    for (const [x, y] of s) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
  const GS = 4; // glyph supersample
  const bw = Math.max(1, Math.ceil((maxX - minX) * scale * GS) + 2);
  const bh = Math.max(1, Math.ceil((maxY - minY) * scale * GS) + 2);
  const hi = new Uint8Array(bw * bh);
  // edges in hi-res bitmap coords: bx = (x-minX)*scale*GS+1, by = (maxY-y)*scale*GS+1
  const edges: [number, number, number, number][] = [];
  for (const s of subs) {
    for (let k = 0; k < s.length; k++) {
      const a = s[k];
      const b = s[(k + 1) % s.length];
      const ax = (a[0] - minX) * scale * GS + 1;
      const ay = (maxY - a[1]) * scale * GS + 1;
      const bx = (b[0] - minX) * scale * GS + 1;
      const by = (maxY - b[1]) * scale * GS + 1;
      if (ay !== by) edges.push([ax, ay, bx, by]);
    }
  }
  for (let y = 0; y < bh; y++) {
    const yc = y + 0.5;
    const xs: number[] = [];
    for (const [ax, ay, bx, by] of edges) {
      if ((ay <= yc && by > yc) || (by <= yc && ay > yc)) {
        xs.push(ax + ((yc - ay) * (bx - ax)) / (by - ay));
      }
    }
    xs.sort((p, q) => p - q);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const x0 = Math.max(0, Math.ceil(xs[k]));
      const x1 = Math.min(bw - 1, Math.floor(xs[k + 1]));
      for (let x = x0; x <= x1; x++) hi[y * bw + x] = 1;
    }
  }
  const w = Math.max(1, Math.ceil((maxX - minX) * scale) + 1);
  const h = Math.max(1, Math.ceil((maxY - minY) * scale) + 1);
  const a = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      let sum = 0;
      for (let dy = 0; dy < GS; dy++) {
        for (let dx = 0; dx < GS; dx++) {
          const hx = x * GS + dx;
          const hy = y * GS + dy;
          if (hx < bw && hy < bh) sum += hi[hy * bw + hx];
        }
      }
      a[y * w + x] = Math.round((sum * 255) / (GS * GS));
    }
  }
  const out: GlyphBmp = {
    w,
    h,
    ox: Math.round(minX * scale),
    oy: Math.round(-maxY * scale),
    a,
  };
  glyphCache.set(key, out);
  return out;
}

function textWidth(text: string, pxSize: number, font: Font, tracking = 0): number {
  let w = 0;
  for (const ch of text) {
    const e = font[ch];
    w += e ? (e[0] * pxSize) / 256 : 0;
  }
  if (text.length > 1) w += tracking * (text.length - 1);
  return w;
}

