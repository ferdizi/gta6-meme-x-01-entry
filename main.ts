type RGB = [number, number, number];

class Layer {
  w: number; // device px
  h: number;
  ss: number;
  buf: Uint8ClampedArray;
  constructor(finalW: number, finalH: number, ss: number) {
    this.ss = ss;
    this.w = Math.round(finalW * ss);
    this.h = Math.round(finalH * ss);
    this.buf = new Uint8ClampedArray(this.w * this.h * 4);
  }
  set(x: number, y: number, c: RGB, a: number): void {
    if (x < 0 || y < 0 || x >= this.w || y >= this.h) return;
    const i = (y * this.w + x) * 4;
    const sa = a / 255;
    if (sa <= 0) return;
    if (sa >= 1) {
      this.buf[i] = c[0];
      this.buf[i + 1] = c[1];
      this.buf[i + 2] = c[2];
      this.buf[i + 3] = 255;
      return;
    }
    const da = this.buf[i + 3] / 255;
    const oa = sa + da * (1 - sa);
    if (oa <= 0) return;
    this.buf[i] = Math.round((c[0] * sa + this.buf[i] * da * (1 - sa)) / oa);
    this.buf[i + 1] = Math.round((c[1] * sa + this.buf[i + 1] * da * (1 - sa)) / oa);
    this.buf[i + 2] = Math.round((c[2] * sa + this.buf[i + 2] * da * (1 - sa)) / oa);
    this.buf[i + 3] = Math.round(oa * 255);
  }
  fillRect(x: number, y: number, w: number, h: number, c: RGB, a = 255): void {
    const x0 = Math.round(x * this.ss);
    const y0 = Math.round(y * this.ss);
    const x1 = Math.round((x + w) * this.ss);
    const y1 = Math.round((y + h) * this.ss);
    for (let yy = y0; yy < y1; yy++) {
      for (let xx = x0; xx < x1; xx++) this.set(xx, yy, c, a);
    }
  }
  // even-odd scanline fill of a polygon, final coords
  fillPoly(pts: Pt[], c: RGB, a = 255): void {
    const d = pts.map(([x, y]): Pt => [Math.round(x * this.ss), Math.round(y * this.ss)]);
    let minY = Infinity, maxY = -Infinity;
    for (const [, y] of d) {
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
    minY = Math.max(0, minY);
    maxY = Math.min(this.h - 1, maxY);
    for (let y = minY; y <= maxY; y++) {
      const xs: number[] = [];
      for (let k = 0; k < d.length; k++) {
        const p = d[k];
        const q = d[(k + 1) % d.length];
        if ((p[1] <= y && q[1] > y) || (q[1] <= y && p[1] > y)) {
          xs.push(p[0] + ((y - p[1]) * (q[0] - p[0])) / (q[1] - p[1]));
        }
      }
      xs.sort((p, q) => p - q);
      for (let k = 0; k + 1 < xs.length; k += 2) {
        const x0 = Math.max(0, Math.ceil(xs[k]));
        const x1 = Math.min(this.w - 1, Math.floor(xs[k + 1]));
        for (let x = x0; x <= x1; x++) this.set(x, y, c, a);
      }
    }
  }
  ellipse(cx: number, cy: number, rx: number, ry: number, c: RGB, a = 255): void {
    const pts: Pt[] = [];
    for (let k = 0; k < 48; k++) {
      const t = (k / 48) * Math.PI * 2;
      pts.push([cx + rx * Math.cos(t), cy + ry * Math.sin(t)]);
    }
    this.fillPoly(pts, c, a);
  }
  roundRect(x: number, y: number, w: number, h: number, r: number, c: RGB, a = 255): void {
    const pts: Pt[] = [];
    const corners: [number, number, number][] = [
      [x + w - r, y + r, -Math.PI / 2],
      [x + w - r, y + h - r, 0],
      [x + r, y + h - r, Math.PI / 2],
      [x + r, y + r, Math.PI],
    ];
    for (const [ccx, ccy, start] of corners) {
      for (let k = 0; k <= 8; k++) {
        const t = start + (k / 8) * (Math.PI / 2);
        pts.push([ccx + r * Math.cos(t), ccy + r * Math.sin(t)]);
      }
    }
    this.fillPoly(pts, c, a);
  }
  // horizontal line, final coords, thickness in final px
  hline(x0: number, x1: number, y: number, t: number, c: RGB, a = 255): void {
    this.fillRect(x0, y - t / 2, x1 - x0, t, c, a);
  }
  dashedHline(x0: number, x1: number, y: number, t: number, c: RGB, dash = 10, gap = 7, a = 255): void {
    let x = x0;
    while (x < x1) {
      const xe = Math.min(x + dash, x1);
      this.fillRect(x, y - t / 2, xe - x, t, c, a);
      x = xe + gap;
    }
  }
  // text: x = left edge (or anchor), baselineY in final coords
  text(x: number, baselineY: number, s: string, pxSize: number, font: Font, c: RGB, align: "left" | "center" | "right" = "left", tracking = 0): void {
    const w = textWidth(s, pxSize, font, tracking);
    let penX = x;
    if (align === "center") penX = x - w / 2;
    if (align === "right") penX = x - w;
    const baseDev = Math.round(baselineY * this.ss);
    for (const ch of s) {
      const e = font[ch];
      if (e && e[1]) {
        const g = glyphBitmap(font, ch, pxSize, this.ss);
        const ox = Math.round(penX * this.ss) + g.ox;
        const oy = baseDev + g.oy;
        for (let gy = 0; gy < g.h; gy++) {
          for (let gx = 0; gx < g.w; gx++) {
            const al = g.a[gy * g.w + gx];
            if (al > 0) this.set(ox + gx, oy + gy, c, al);
          }
        }
      }
      if (e) penX += (e[0] * pxSize) / 256 + tracking;
    }
  }
}

// Rotate-blit src layer onto dst, centered at (cx, cy) final coords, degrees.
function blitRotated(dst: Layer, src: Layer, cx: number, cy: number, deg: number, alpha = 255): void {
  const rad = (deg * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);
  const dcx = cx * dst.ss;
  const dcy = cy * dst.ss;
  const scx = src.w / 2;
  const scy = src.h / 2;
  const r = Math.hypot(src.w / 2, src.h / 2);
  const y0 = Math.max(0, Math.floor(dcy - r));
  const y1 = Math.min(dst.h - 1, Math.ceil(dcy + r));
  const x0 = Math.max(0, Math.floor(dcx - r));
  const x1 = Math.min(dst.w - 1, Math.ceil(dcx + r));
  for (let y = y0; y <= y1; y++) {
    for (let x = x0; x <= x1; x++) {
      const dx = x - dcx;
      const dy = y - dcy;
      const sx = scx + dx * cos + dy * sin;
      const sy = scy - dx * sin + dy * cos;
      if (sx < 0 || sy < 0 || sx >= src.w - 1 || sy >= src.h - 1) continue;
      const fx = Math.floor(sx);
      const fy = Math.floor(sy);
      const tx = sx - fx;
      const ty = sy - fy;
      const sample = (ox: number, oy: number): number => {
        const i = ((fy + oy) * src.w + (fx + ox)) * 4;
        return i;
      };
      let rr = 0, gg = 0, bb = 0, aa = 0;
      const w00 = (1 - tx) * (1 - ty), w10 = tx * (1 - ty), w01 = (1 - tx) * ty, w11 = tx * ty;
      const idx = [sample(0, 0), sample(1, 0), sample(0, 1), sample(1, 1)];
      const ws = [w00, w10, w01, w11];
      for (let k = 0; k < 4; k++) {
        const i = idx[k];
        rr += src.buf[i] * ws[k];
        gg += src.buf[i + 1] * ws[k];
        bb += src.buf[i + 2] * ws[k];
        aa += src.buf[i + 3] * ws[k];
      }
      const a = Math.round((aa * alpha) / 255);
      if (a > 0) dst.set(x, y, [Math.round(rr), Math.round(gg), Math.round(bb)], a);
    }
  }
}

// ---------------------------------------------------------------------------
// PNG encoder (stdlib zlib). Deterministic: fixed filters, level 9.
// ---------------------------------------------------------------------------

const CRC_TABLE: Uint32Array = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf: Buffer): number {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function pngChunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td), 0);
  return Buffer.concat([len, td, crc]);
}

function encodePNG(rgba: Uint8Array, w: number, h: number): Buffer {
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) {
    raw[y * (w * 4 + 1)] = 0; // filter: none
    raw.set(rgba.subarray(y * w * 4, (y + 1) * w * 4), y * (w * 4 + 1) + 1);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // color type RGBA
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk("IHDR", ihdr),
    pngChunk("IDAT", deflateSync(raw, { level: 9 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

// Downsample a 2x layer to final-size RGBA.
function downsample(layer: Layer): Uint8Array {
  const out = new Uint8Array(layer.w / layer.ss * (layer.h / layer.ss) * 4);
  const fw = layer.w / layer.ss;
  const fh = layer.h / layer.ss;
  const ss = layer.ss;
  for (let y = 0; y < fh; y++) {
    for (let x = 0; x < fw; x++) {
      let r = 0, g = 0, b = 0, a = 0;
      for (let dy = 0; dy < ss; dy++) {
        for (let dx = 0; dx < ss; dx++) {
          const i = ((y * ss + dy) * layer.w + (x * ss + dx)) * 4;
          r += layer.buf[i];
          g += layer.buf[i + 1];
          b += layer.buf[i + 2];
          a += layer.buf[i + 3];
        }
      }
      const n = ss * ss;
      const o = (y * fw + x) * 4;
      out[o] = Math.round(r / n);
      out[o + 1] = Math.round(g / n);
      out[o + 2] = Math.round(b / n);
      out[o + 3] = Math.round(a / n);
    }
  }
  return out;
}

